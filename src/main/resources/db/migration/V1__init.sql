CREATE TABLE users (
                       id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(255)
);

CREATE TABLE films (
                       id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name         VARCHAR(255),
                       release_year INTEGER,
                       platform     VARCHAR(255),
                       genre        VARCHAR(255),
                       tmdb_id      BIGINT,
                       overview     VARCHAR(2000),
                       poster_path  VARCHAR(255),
                       CONSTRAINT uk_films_tmdb_id UNIQUE (tmdb_id)
);

CREATE TABLE rooms (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       invite_code VARCHAR(6) NOT NULL,
                       creator_id  BIGINT     NOT NULL,
                       partner_id  BIGINT,
                       CONSTRAINT uk_rooms_invite_code UNIQUE (invite_code),
                       CONSTRAINT fk_rooms_creator FOREIGN KEY (creator_id) REFERENCES users (id),
                       CONSTRAINT fk_rooms_partner FOREIGN KEY (partner_id) REFERENCES users (id)
);

CREATE TABLE swipes (
                        id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        room_id BIGINT  NOT NULL,
                        user_id BIGINT  NOT NULL,
                        film_id BIGINT  NOT NULL,
                        liked   BOOLEAN NOT NULL,
                        CONSTRAINT uk_swipes_room_user_film UNIQUE (room_id, user_id, film_id),
                        CONSTRAINT fk_swipes_room FOREIGN KEY (room_id) REFERENCES rooms (id),
                        CONSTRAINT fk_swipes_user FOREIGN KEY (user_id) REFERENCES users (id),
                        CONSTRAINT fk_swipes_film FOREIGN KEY (film_id) REFERENCES films (id)
);